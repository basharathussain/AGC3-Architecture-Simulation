def _paired(rows: list[M.Metrics], arm_a: str, arm_b: str, env: str, field,
            keep=lambda ra, rb: True) -> tuple[list[float], list[float]]:
    """Seed-aligned samples for two arms in one environment.

    The runner hands every arm the same `World(seed)`, so seed is the pairing
    key. `_by` discards it; this keeps it. A seed is used only when both arms
    have a record for it and `keep` accepts the pair, so the two lists are the
    same length and index *i* is the same seed in both.
    """
    a = {r.seed: r for r in rows if r.arm == arm_a and r.env == env}
    b = {r.seed: r for r in rows if r.arm == arm_b and r.env == env}
    seeds = sorted(set(a) & set(b))
    pairs = [(a[s], b[s]) for s in seeds if keep(a[s], b[s])]
    return [float(field(ra)) for ra, _ in pairs], [float(field(rb)) for _, rb in pairs]


def significance(rows: list[M.Metrics], extra: list[Comparison] | None = None):
    """H1-H4 against the strongest baseline, as PAIRED comparisons.

    The comparator is B2, the strongest baseline here and the one holding the
    Security specialist; comparing against the weakest would inflate every
    effect.

    Inference is paired because the design is. Every arm sees the same
    `World(seed)`, so arm *k* at seed *s* faces byte-identically what arm *j* at
    seed *s* faces, and the seeds are matched rather than two independent
    samples. The submitted version used an independent-samples test here, which
    discards that matching -- the same mistake `compare_paired` was written to
    avoid for the misspecification sweep. Discarding it is conservative rather
    than permissive: it costs power and cannot manufacture an effect, which is
    why the unpaired *p* is reported alongside rather than quietly replaced.

    Completion and recovery are binary, so the paired instrument is McNemar's
    exact test on the discordant seeds; violations and activations are counts,
    so theirs is the signed-rank test.
    """
    comps: list[Comparison] = []

    def add(label, arm_a, arm_b, env, field, binary, keep=lambda ra, rb: True):
        a, b = _paired(rows, arm_a, arm_b, env, field, keep)
        c = (compare_paired_binary if binary else compare_paired)(label, a, b)
        # The same comparison as submitted, for the side-by-side column.
        u = compare(label, a, b)
        comps.append(Comparison(**{**c.to_dict(), "p_unpaired": u.p_raw}))

    for env in ("nominal", "perturbed"):
        add(f"H1 completion, {env} (A2 vs B2)", "A2", "B2", env,
            lambda r: r.success, binary=True)
        add(f"H2 recovery, {env} (A2 vs B2)", "A2", "B2", env,
            lambda r: r.success, binary=True,
            keep=lambda ra, rb: ra.had_failure and rb.had_failure)
    add("H3 violations, nominal (A2 vs A1)", "A2", "A1", "nominal",
        lambda r: r.violations, binary=False)
    # H4 overhead is measured in **agent activations**, not wall-clock.
    #
    # Wall-clock in Tier 1 measures how fast the simulation runs, which is a
    # property of Python and of nothing under study; reporting it as
    # "adaptation overhead" would be meaningless at best and misleading at
    # worst. Agent activations are the invocation cost that would translate
    # into real latency and tokens under Tier 2, so that is what is tested.
    add("H4 agent activations, nominal (A2 vs B2)", "A2", "B2", "nominal",
        lambda r: r.agent_activations, binary=False)

    if extra:
        comps.extend(extra)
    comps = holm(comps)

    out = [
        PREAMBLE,
        r"\begin{table*}[t]",
        r"\caption{Paired comparisons across matched seeds. Completion and "
        r"recovery use McNemar's exact test on discordant seeds; violations, "
        r"activations and the misspecification sweep use the Wilcoxon "
        r"signed-rank test. Effect size is Cliff's $\delta$, which for a binary "
        r"outcome coincides with the matched-pairs estimator. Holm--Bonferroni "
        r"corrected across the family at $\alpha=0.05$. $p_{\text{unpaired}}$ "
        r"is the independent-samples value reported in the submitted version, "
        r"shown for comparison; discarding the pairing is conservative, so it "
        r"is the larger of the two.}",
        r"\label{tab:stats}",
        r"\centering\footnotesize",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r"Comparison & $p_{\text{raw}}$ & $p_{\text{Holm}}$ & "
        r"$p_{\text{unpaired}}$ & $\delta$ & Magnitude \\",
        r"\midrule",
    ]
    for c in comps:
        star = r"$^{*}$" if c.significant else ""
        pu = "--" if c.p_unpaired is None else f"{c.p_unpaired:.4f}"
        out.append(
            f"{c.label} & {c.p_raw:.4f} & {c.p_holm:.4f}{star} & {pu} & "
            f"{c.delta:+.3f} & {c.magnitude} " + r"\\"
        )
    out += [
        r"\bottomrule",
        r"\end{tabular}}",
        r"\\[2pt]\footnotesize $^{*}$ significant after Holm--Bonferroni "
        r"correction. $\delta>0$ favours AGCCC on completion and recovery; on "
        r"agent activations $\delta>0$ would indicate \emph{higher} cost. "
        r"Overhead is reported as agent activations rather than wall-clock, "
        r"which under simulated agents measures the harness rather than the "
        r"architecture.",
        r"\end{table*}",
        "",
    ]
    return "\n".join(out), comps


def power_note(rows_30: list[M.Metrics], rows_100: list[M.Metrics]) -> str:
    """The n=30 primary, with the n=100 run as a consistency check.

    This note previously argued that the perturbed comparison failed at n=30 for
    want of power, since the same effect reached significance at n=100. That
    argument belonged to the independent-samples test: paired at n=30 the
    perturbed comparison is already significant, so there is no power shortfall
    left to explain.

    What the n=100 run still does is check that the effect does not depend on
    the depth chosen in advance. It is reported as a supplementary consistency
    check and nothing is promoted to primary on its account -- the pre-specified
    n=30 remains the primary depth.

    Both the paired and the unpaired value are emitted at each depth, so the
    manuscript can state what changed when the test was corrected.
    """

    def gap(rows, env):
        a = {r.seed: r for r in rows if r.arm == "A2" and r.env == env}
        b = {r.seed: r for r in rows if r.arm == "B2" and r.env == env}
        seeds = sorted(set(a) & set(b))
        xs = [float(a[s].success) for s in seeds]
        ys = [float(b[s].success) for s in seeds]
        return compare_paired_binary(env, xs, ys), compare(env, xs, ys)

    (p30, u30), (p100, u100) = gap(rows_30, "perturbed"), gap(rows_100, "perturbed")
    return (
        PREAMBLE
        + "% Supplementary check, perturbed environment, A2 vs B2.\n"
        + f"\\newcommand{{\\perturbedPRaw}}{{{p30.p_raw:.4f}}}\n"
        + f"\\newcommand{{\\perturbedPUnpaired}}{{{u30.p_raw:.4f}}}\n"
        + f"\\newcommand{{\\perturbedDelta}}{{{p30.delta:+.3f}}}\n"
        + f"\\newcommand{{\\perturbedPHundred}}{{{p100.p_raw:.4f}}}\n"
        + f"\\newcommand{{\\perturbedPHundredUnpaired}}{{{u100.p_raw:.4f}}}\n"
        + f"\\newcommand{{\\perturbedDeltaHundred}}{{{p100.delta:+.3f}}}\n"
    )


# --- E1 trace ------------------------------------------------------------


def e1_trace(records: list[dict]) -> tuple[str, dict | None]:
    """The candidate-score trace across successive Tester rejections.

    Selection is by an explicit, stated rule rather than by eye: the first seed
    (in ascending order) whose governed run contains at least three decisions
    and in which the selected action changes at least twice. Reporting a
    hand-picked trace would be indistinguishable from reporting the nicest one.
    """
    best = None
    for r in sorted(
        (x for x in records if x["arm"] == "A2" and x["env"] == "nominal"),
        key=lambda x: x["seed"],
    ):
        trace = r.get("decisions_trace", [])
        if len(trace) < 3:
            continue
        selections = [d["selected"] for d in trace]
        switches = sum(1 for i in range(1, len(selections)) if selections[i] != selections[i - 1])
        if switches >= 2:
            best = r
            break
    if best is None:
        return PREAMBLE + "% no qualifying E1 trace found\n", None

    trace = best["decisions_trace"]
    actions = [a.value for a in Action]
    out = [
        PREAMBLE,
        r"\begin{table*}[t]",
        rf"\caption{{Candidate scores at successive verification rounds "
        rf"(seed~{best['seed']}, governed arm). $\hat{{p}}$ is the "
        rf"Laplace-smoothed success posterior; $J$ is the objective. Actions "
        rf"struck out were removed by the admissibility filter and were never "
        rf"scored. The selected action changes without any rule mandating it.}}",
        r"\label{tab:e1}",
        r"\centering\footnotesize",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{cc" + "c" * len(actions) + "c}",
        r"\toprule",
        r"Round & $c$ & " + " & ".join(a.replace("_", r"\_") for a in actions) + r" & Selected \\",
        r"\midrule",
    ]
    for i, d in enumerate(trace, start=1):
        cells = []
        for a in actions:
            if a in d.get("rejected", {}):
                cells.append(r"\textemdash")
            elif a in d.get("scores", {}):
                p = d.get("p_success", {}).get(a)
                cells.append(
                    f"{d['scores'][a]:.3f}" + (rf"\,\tiny({p:.2f})" if p is not None else "")
                )
            else:
                cells.append("--")
        sel = (d["selected"] or "none").replace("_", r"\_")
        out.append(
            f"{i} & {d['confidence']:.3f} & " + " & ".join(cells) + rf" & \textbf{{{sel}}} \\"
        )
    out += [
        r"\bottomrule",
        r"\end{tabular}}",
        r"\\[2pt]\footnotesize Cell entries are $J$ with $\hat{p}$ in parentheses; "
        r"\textemdash{} marks an inadmissible action.",
        r"\end{table*}",
        "",
    ]
    return "\n".join(out), best


