"""Emit the paper's tables and figures.

Every number the paper prints is written from here, and the paper `\\input{}`s
the result. Nothing is transcribed by hand, so re-running the experiment
regenerates the paper's evidence and a stale figure is impossible.

The LaTeX produced targets the `cas-dc` document already in
`Articles/Article#1-Foundation/agccc_foundation.tex` and uses only `booktabs`,
which that document already loads.
"""

