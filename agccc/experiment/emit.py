def sensitivity_table(sweep: list[dict], grid: list[dict]) -> str:
    out = [
        PREAMBLE,
        r"\begin{table*}[t]",
        r"\caption{Sensitivity. Upper: the risk weight $\lambda_R$, which "
        r"governs whether a \emph{soft} penalty can substitute for the "
        r"\emph{hard} admissibility constraint. Lower: agent-competence "
        r"parameters of the simulated world. The governed arm is invariant "
        r"across both sweeps.}",
        r"\label{tab:sensitivity}",
        r"\centering\footnotesize",
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"$\lambda_R$ & A1 compl. (\%) & A1 viol. & A2 compl. (\%) & A2 viol. \\",
        r"\midrule",
    ]
    for s in sweep:
        out.append(
            f"{s['lambda_risk']:.2f} & {100 * s['A1_success']:.1f} & {s['A1_violations']} & "
            f"{100 * s['A2_success']:.1f} & {s['A2_violations']} " + r"\\"
        )
    out += [
        r"\midrule",
        r"$p^{\text{sec}}_{\text{coder}}$ / $p^{\text{sec}}_{\text{spec}}$ & "
        r"\multicolumn{2}{c}{B2 compl. (\%)} & \multicolumn{2}{c}{A2 compl. (\%)} \\",
        r"\midrule",
    ]
    for g in grid:
        out.append(
            f"{g['p_fix_security_coder']:.2f} / {g['p_fix_security_specialist']:.2f} & "
            rf"\multicolumn{{2}}{{c}}{{{100 * g['B2_success']:.1f}}} & "
            rf"\multicolumn{{2}}{{c}}{{{100 * g['A2_success']:.1f}}} \\"
        )
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(out)
