PREAMBLE = (
    "% Generated by agccc.experiment.emit -- do not edit by hand.\n"
    "% Regenerate with:  python -m agccc.experiment.emit\n"
)


def _pct(x: float) -> str:
    return "--" if x != x else f"{100 * x:.1f}"


def _sci(p: float) -> str:
    """A p-value as LaTeX maths rather than Python's `1.88e-04`."""
    if p != p:
        return r"\mathrm{n/a}"
    if p >= 1e-3:
        return f"{p:.4f}"
    mantissa, exponent = f"{p:.2e}".split("e")
    return rf"{mantissa}\times 10^{{{int(exponent)}}}"


def _by(rows: list[M.Metrics], arm: str, env: str) -> list[M.Metrics]:
    return [r for r in rows if r.arm == arm and r.env == env]


# --- Table III -----------------------------------------------------------


def table3(rows: list[M.Metrics]) -> str:
    out = [
        PREAMBLE,
        r"\begin{table*}[t]",
        r"\caption{Main comparison of the three baselines with the proposed "
        r"architecture under nominal and perturbed execution. Simulated agent "
        r"execution, derived (Mode~B) confidence, $n=30$ per arm per environment.}",
        r"\label{tab:main}",
        r"\centering\small",
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"System & Task Completion & Recovery & Policy & Adapt. \\",
        r" & (\%) & (\%) & compliance (\%) & count \\",
        r"\midrule",
    ]
    for env in ("nominal", "perturbed"):
        out.append(rf"\multicolumn{{5}}{{l}}{{\emph{{{env.capitalize()}}}}} \\")
        for arm in A.MAIN_ARMS:
            s = _by(rows, arm, env)
            label = A.ARM_LABELS[arm]
            if arm == "A2":
                label = r"\textbf{" + label + "}"
            out.append(
                f"{label} & {_pct(M.rate(s, 'success'))} & "
                f"{_pct(M.recovery_rate(s))} & {_pct(M.compliance_rate(s))} & "
                f"{M.mean(s, 'adaptations'):.1f} " + r"\\"
            )
        if env == "nominal":
            out.append(r"\midrule")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(out)


