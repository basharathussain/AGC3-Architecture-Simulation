def misspecification(sweep: list[dict]) -> tuple[str, Comparison]:
    """E5 table — compliance under utility misspecification.

    Reports the worst case per arm, because that is what a guarantee means. The
    full family is in `reproducibility.json`; nothing is selected for effect.
    """
    a1c = [s["A1_compliance"] for s in sweep]
    a2c = [s["A2_compliance"] for s in sweep]
    a1s = [s["A1_success"] for s in sweep]
    a2s = [s["A2_success"] for s in sweep]
    a1_bad = sum(1 for c in a1c if c < 1.0)
    a2_bad = sum(1 for c in a2c if c < 1.0)
    comp = compare_paired("H3 compliance under misspecification (A2 vs A1)", a2c, a1c)

    out = [
        PREAMBLE,
        r"\begin{table}[t]",
        rf"\caption{{Compliance under utility misspecification. Each of the "
        rf"{len(sweep)} scoring configurations varies $\lambda_R$, $\lambda_C$ "
        rf"and the release-risk constant over plausible authored values; every "
        rf"configuration is run for $n=30$ seeds on both arms "
        rf"({2 * 30 * len(sweep)} runs). The governed arm is compliant in every "
        rf"configuration; the ungoverned arm is compliant only in those where "
        rf"the penalty happens to dominate.}}",
        r"\label{tab:misspec}",
        r"\centering\footnotesize",
        r"\begin{tabular}{lcc}",
        r"\toprule",
        r" & A1: ungoverned & \textbf{A2: governed} \\",
        r"\midrule",
        rf"Compliance, best configuration (\%) & {100 * max(a1c):.1f} & "
        rf"\textbf{{{100 * max(a2c):.1f}}} \\",
        rf"\textbf{{Compliance, worst configuration (\%)}} & {100 * min(a1c):.1f} & "
        rf"\textbf{{{100 * min(a2c):.1f}}} \\",
        rf"Mean compliance (\%) & {100 * sum(a1c) / len(a1c):.1f} & "
        rf"\textbf{{{100 * sum(a2c) / len(a2c):.1f}}} \\",
        rf"Configurations admitting a violation & {a1_bad}\,/\,{len(sweep)} & "
        rf"\textbf{{{a2_bad}\,/\,{len(sweep)}}} \\",
        r"\midrule",
        rf"Completion, worst configuration (\%) & {100 * min(a1s):.1f} & "
        rf"\textbf{{{100 * min(a2s):.1f}}} \\",
        rf"Completion, best configuration (\%) & {100 * max(a1s):.1f} & "
        rf"{100 * max(a2s):.1f} \\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\\[2pt]\footnotesize Wilcoxon signed-rank over matched "
        rf"configurations: $p={_sci(comp.p_raw)}$, Cliff's $\delta={comp.delta:+.3f}$ "
        rf"({comp.magnitude}).",
        r"\end{table}",
        "",
    ]
    return "\n".join(out), comp


def significance(rows: list[M.Metrics], extra: list[Comparison] | None = None):
    """H1-H4 as two-sample rank tests against the strongest baseline.

    The comparator is B2, which is the strongest baseline in this experiment and
    the one with the Security specialist in its roster. Comparing against the
    weakest baseline would inflate every effect.
    """
    comps: list[Comparison] = []
    for env in ("nominal", "perturbed"):
        a2 = _by(rows, "A2", env)
        b2 = _by(rows, "B2", env)
        comps.append(
            compare(
                f"H1 completion, {env} (A2 vs B2)",
                [float(r.success) for r in a2],
                [float(r.success) for r in b2],
            )
        )
        comps.append(
            compare(
                f"H2 recovery, {env} (A2 vs B2)",
                [float(r.success) for r in a2 if r.had_failure],
                [float(r.success) for r in b2 if r.had_failure],
            )
        )
    comps.append(
        compare(
            "H3 violations, nominal (A2 vs A1)",
            [float(r.violations) for r in _by(rows, "A2", "nominal")],
            [float(r.violations) for r in _by(rows, "A1", "nominal")],
        )
    )
    # H4 overhead is measured in **agent activations**, not wall-clock.
    #
    # Wall-clock in Tier 1 measures how fast the simulation runs, which is a
    # property of Python and of nothing under study; reporting it as
    # "adaptation overhead" would be meaningless at best and misleading at
    # worst. Agent activations are the invocation cost that would translate
    # into real latency and tokens under Tier 2, so that is what is tested.
    comps.append(
        compare(
            "H4 agent activations, nominal (A2 vs B2)",
            [float(r.agent_activations) for r in _by(rows, "A2", "nominal")],
            [float(r.agent_activations) for r in _by(rows, "B2", "nominal")],
        )
    )
    if extra:
        comps.extend(extra)
    comps = holm(comps)

    out = [
        PREAMBLE,
        r"\begin{table*}[t]",
        r"\caption{Two-sample comparisons. Mann--Whitney~$U$ (two-sided) with "
        r"Cliff's $\delta$, Holm--Bonferroni corrected across the family at "
        r"$\alpha=0.05$.}",
        r"\label{tab:stats}",
        r"\centering\footnotesize",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r"Comparison & $U$ & $p_{\text{raw}}$ & $p_{\text{Holm}}$ & "
        r"$\delta$ & Magnitude \\",
        r"\midrule",
    ]
    for c in comps:
        u = "--" if c.u != c.u else f"{c.u:.1f}"
        star = r"$^{*}$" if c.significant else ""
        out.append(
            f"{c.label} & {u} & {c.p_raw:.4f} & {c.p_holm:.4f}{star} & "
            f"{c.delta:+.3f} & {c.magnitude} " + r"\\"
        )
    out += [
        r"\bottomrule",
        r"\end{tabular}}",
        r"\\[2pt]\footnotesize $^{*}$ significant after Holm--Bonferroni "
        r"correction. $\delta>0$ favours AGCCC on completion and recovery; on "
        r"agent activations $\delta>0$ would indicate \emph{higher} cost. "
        r"Overhead is reported as agent activations rather than wall-clock, "
        r"which under simulated agents measures the harness rather than the "
        r"architecture.",
        r"\end{table*}",
        "",
    ]
    return "\n".join(out), comps


def power_note(rows_30: list[M.Metrics], rows_100: list[M.Metrics]) -> str:
    """A pre-registered n=30 primary, plus an honest note on its power.

    The perturbed comparison does not reach significance at n=30 while showing
    the same effect size that is significant at n=100. That is a power
    limitation, and saying so is different from — and more useful than — either
    quietly raising n until the result appears, or reporting "no effect".
    """

    def gap(rows, env):
        a = [float(r.success) for r in rows if r.arm == "A2" and r.env == env]
        b = [float(r.success) for r in rows if r.arm == "B2" and r.env == env]
        return compare(env, a, b)

    c30, c100 = gap(rows_30, "perturbed"), gap(rows_100, "perturbed")
    return (
        PREAMBLE
        + "% Supplementary power analysis, perturbed environment, A2 vs B2.\n"
        + f"\\newcommand{{\\perturbedPRaw}}{{{c30.p_raw:.4f}}}\n"
        + f"\\newcommand{{\\perturbedDelta}}{{{c30.delta:+.3f}}}\n"
        + f"\\newcommand{{\\perturbedPHundred}}{{{c100.p_raw:.4f}}}\n"
        + f"\\newcommand{{\\perturbedDeltaHundred}}{{{c100.delta:+.3f}}}\n"
    )


# --- E1 trace ------------------------------------------------------------


def e1_trace(records: list[dict]) -> tuple[str, dict | None]:
    """The candidate-score trace across successive Tester rejections.

    Selection is by an explicit, stated rule rather than by eye: the first seed
    (in ascending order) whose governed run contains at least three decisions
    and in which the selected action changes at least twice. Reporting a
    hand-picked trace would be indistinguishable from reporting the nicest one.
    """
    best = None
    for r in sorted(
        (x for x in records if x["arm"] == "A2" and x["env"] == "nominal"),
        key=lambda x: x["seed"],
    ):
        trace = r.get("decisions_trace", [])
        if len(trace) < 3:
            continue
        selections = [d["selected"] for d in trace]
        switches = sum(1 for i in range(1, len(selections)) if selections[i] != selections[i - 1])
        if switches >= 2:
            best = r
            break
    if best is None:
        return PREAMBLE + "% no qualifying E1 trace found\n", None

    trace = best["decisions_trace"]
    actions = [a.value for a in Action]
    out = [
        PREAMBLE,
        r"\begin{table*}[t]",
        rf"\caption{{Candidate scores at successive verification rounds "
        rf"(seed~{best['seed']}, governed arm). $\hat{{p}}$ is the "
        rf"Laplace-smoothed success posterior; $J$ is the objective. Actions "
        rf"struck out were removed by the admissibility filter and were never "
        rf"scored. The selected action changes without any rule mandating it.}}",
        r"\label{tab:e1}",
        r"\centering\footnotesize",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{cc" + "c" * len(actions) + "c}",
        r"\toprule",
        r"Round & $c$ & " + " & ".join(a.replace("_", r"\_") for a in actions) + r" & Selected \\",
        r"\midrule",
    ]
    for i, d in enumerate(trace, start=1):
        cells = []
        for a in actions:
            if a in d.get("rejected", {}):
                cells.append(r"\textemdash")
            elif a in d.get("scores", {}):
                p = d.get("p_success", {}).get(a)
                cells.append(
                    f"{d['scores'][a]:.3f}" + (rf"\,\tiny({p:.2f})" if p is not None else "")
                )
            else:
                cells.append("--")
        sel = (d["selected"] or "none").replace("_", r"\_")
        out.append(
            f"{i} & {d['confidence']:.3f} & " + " & ".join(cells) + rf" & \textbf{{{sel}}} \\"
        )
    out += [
        r"\bottomrule",
        r"\end{tabular}}",
        r"\\[2pt]\footnotesize Cell entries are $J$ with $\hat{p}$ in parentheses; "
        r"\textemdash{} marks an inadmissible action.",
        r"\end{table*}",
        "",
    ]
    return "\n".join(out), best


# --- figures -------------------------------------------------------------


def figures(rows: list[M.Metrics], sweep: list[dict], out_dir: Path,
            misspec: list[dict] | None = None) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update(
        {"font.size": 8, "font.family": "serif", "axes.grid": True, "grid.alpha": 0.3}
    )

    # --- Figure 2: completion and recovery, nominal vs perturbed ---------
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.6))
    labels = [A.ARM_LABELS[a].split(":")[0] for a in A.MAIN_ARMS]
    x = range(len(A.MAIN_ARMS))
    width = 0.38

    for ax, (metric, title) in zip(
        axes, (("success", "Task completion"), ("recovery", "Recovery after failure"))
    ):
        for k, env in enumerate(("nominal", "perturbed")):
            vals = []
            for arm in A.MAIN_ARMS:
                s = _by(rows, arm, env)
                v = M.rate(s, "success") if metric == "success" else M.recovery_rate(s)
                vals.append(0.0 if v != v else 100 * v)
            ax.bar(
                [i + (k - 0.5) * width for i in x],
                vals,
                width,
                label=env,
                color=("#3B6EA5" if k == 0 else "#C4623D"),
                edgecolor="black",
                linewidth=0.4,
            )
        ax.set_xticks(list(x))
        ax.set_xticklabels(labels)
        ax.set_ylim(0, 105)
        ax.set_ylabel("%")
        ax.set_title(title)
    axes[0].legend(frameon=False, loc="upper left")
    fig.tight_layout()
    fig.savefig(out_dir / "fig2.pdf")
    plt.close(fig)

    # --- Figure 3: governance -------------------------------------------
    ncols = 3 if misspec else 2
    fig, axes = plt.subplots(1, ncols, figsize=(3.5 * ncols, 2.6))

    ax = axes[0]
    for k, env in enumerate(("nominal", "perturbed")):
        vals = [100 * M.compliance_rate(_by(rows, a, env)) for a in A.MAIN_ARMS]
        ax.bar(
            [i + (k - 0.5) * width for i in x],
            vals,
            width,
            label=env,
            color=("#3B6EA5" if k == 0 else "#C4623D"),
            edgecolor="black",
            linewidth=0.4,
        )
    ax.set_xticks(list(x))
    ax.set_xticklabels(labels)
    ax.set_ylim(0, 105)
    ax.set_ylabel("%")
    ax.set_title("Policy compliance")
    ax.legend(frameon=False, loc="lower right")

    # The λ_R sweep: does a soft penalty substitute for a hard constraint?
    ax = axes[1]
    lam = [s["lambda_risk"] for s in sweep]
    ax.plot(lam, [s["A1_violations"] for s in sweep], "o-", color="#C4623D",
            label="ungoverned (A1)")
    ax.plot(lam, [s["A2_violations"] for s in sweep], "s-", color="#3B6EA5",
            label="governed (A2)")
    ax.set_xlabel(r"risk weight $\lambda_R$")
    ax.set_ylabel("policy violations (30 runs)")
    ax.set_title("Soft penalty vs hard constraint")
    ax.legend(frameon=False)

    # Panel 3: every scoring configuration, sorted by the ungoverned arm's
    # compliance. The governed arm is a flat line at 100%; the ungoverned arm
    # falls away wherever the penalty fails to dominate. This is the shape of a
    # guarantee versus the shape of a hope.
    if misspec:
        ax = axes[2]
        order = sorted(range(len(misspec)), key=lambda i: misspec[i]["A1_compliance"])
        xs = range(len(order))
        ax.plot(xs, [100 * misspec[i]["A1_compliance"] for i in order], "o-",
                color="#C4623D", ms=3, label="ungoverned (A1)")
        ax.plot(xs, [100 * misspec[i]["A2_compliance"] for i in order], "s-",
                color="#3B6EA5", ms=3, label="governed (A2)")
        ax.set_xlabel("scoring configuration (sorted)")
        ax.set_ylabel("compliance (%)")
        ax.set_ylim(-5, 105)
        ax.set_title("Utility misspecification")
        ax.legend(frameon=False, loc="lower right")

    fig.tight_layout()
    fig.savefig(out_dir / "fig3.pdf")
    plt.close(fig)


